#!/bin/bash
# dsh-chrome-bridge installer (idempotent — safe to re-run)
#
#   ./install.sh              install / update
#   ./install.sh --uninstall  remove everything except the Chrome extension itself
#
# What it does:
#   1. copies the extension + native host into ~/.dsh/chrome-bridge/ (repo can move afterwards)
#   2. registers the native messaging host with Chrome, bound to the extension's fixed ID
#      (plus the Chrome Web Store build's ID)
#   3. installs the `cb` CLI, the `dsh-chrome-bridge` manager, and the DSH skill
#
# 平时用不着跑它：DSH 插件的 setup.js 在首次加载时会自动做 1~3 步（宿主 + 注册文件），
# 装法就是 `dsh plugin add <tarball>`。这个脚本是给「用源码开发 / 想装 cb 命令行」的人用的，
# 做的事和插件里的 setup.js 一致，结果落在同样的位置。
#
# The extension ID is derived from the public key embedded in the extension manifest,
# so it is the same on every machine — the registration file never needs editing.

set -euo pipefail

REPO="$(cd "$(dirname "$0")" && pwd)"
VENDOR="$REPO/plugin/vendor"
BRIDGE="$HOME/.dsh/chrome-bridge"
# The extension lives in a VISIBLE folder on purpose: Chrome's "Load unpacked" file
# picker cannot reach hidden directories without ⌘⇧G.
EXT_DIR="$HOME/dsh-bridge-extension"
HOST_NAME="com.dsh.bridge"
NM_DIR="$HOME/Library/Application Support/Google/Chrome/NativeMessagingHosts"
NM_FILE="$NM_DIR/$HOST_NAME.json"

if [ "${1:-}" = "--uninstall" ]; then
  rm -f "$NM_FILE"
  rm -rf "/tmp/dsh-bridge-$(id -u)"
  rm -f /tmp/dsh-bridge.sock /tmp/dsh-bridge.token /tmp/dsh-bridge.log   # older versions kept them here
  rm -rf "$BRIDGE" "$EXT_DIR"
  rm -f "$HOME/.dsh/bin/cb" "$HOME/.dsh/bin/dsh-chrome-bridge"
  for L in cb dsh-chrome-bridge; do   # only our own links, never the user's own command of the same name
    if [ "$(readlink "$HOME/.local/bin/$L" 2>/dev/null)" = "$HOME/.dsh/bin/$L" ]; then rm -f "$HOME/.local/bin/$L"; fi
  done
  rm -rf "$HOME/.dsh/skills/browser"
  echo "Removed: native host registration, host dir, extension dir, cb, manager, skill."
  echo "The Chrome extension itself must be removed at chrome://extensions (Chrome Bridge)."
  exit 0
fi

# ── prerequisites ───────────────────────────────────────────────────────────
if [ "$(uname)" != "Darwin" ]; then
  echo "This bridge is macOS-only for now (the native messaging path is macOS-specific)." >&2
  exit 1
fi
NODE_BIN=""
for N in "${DSH_BRIDGE_NODE:-}" /usr/local/bin/node "$HOME/.local/bin/node" /opt/homebrew/bin/node; do
  if [ -n "$N" ] && [ -x "$N" ]; then NODE_BIN="$N"; break; fi
done
if [ -z "$NODE_BIN" ]; then
  echo "node not found. Install Node.js, or point DSH_BRIDGE_NODE at its absolute path." >&2
  exit 1
fi

echo "==> 1/6 native host -> $BRIDGE"
mkdir -p "$BRIDGE/host" "$EXT_DIR" "$HOME/.dsh/bin" "$HOME/.dsh/chrome-cursor"
cp -R "$VENDOR/extension/." "$EXT_DIR/"
cp "$VENDOR/host/host.js" "$VENDOR/host/run.sh" "$BRIDGE/host/"
cp "$VENDOR/in-page-cursor.js" "$HOME/.dsh/chrome-cursor/in-page-cursor.js"
chmod +x "$BRIDGE/host/run.sh"

echo "==> 2/6 extension ID (derived from the manifest key; fixed forever)"
EXT_ID="$("$NODE_BIN" -e '
const fs=require("fs"),crypto=require("crypto");
const key=JSON.parse(fs.readFileSync(process.argv[1],"utf8")).key;
const hex=crypto.createHash("sha256").update(Buffer.from(key,"base64")).digest("hex").slice(0,32);
console.log([...hex].map(c=>String.fromCharCode(97+parseInt(c,16))).join(""));
' "$EXT_DIR/manifest.json")"
echo "    $EXT_ID"

echo "==> 3/6 register native messaging host"
# 本地「加载已解压」的固定 ID + 商店版 ID（列表在 plugin/setup.js 的 STORE_EXT_IDS，两边共用一份）
ORIGINS="$("$NODE_BIN" -e '
import(process.argv[1]).then((m) => console.log(JSON.stringify(
  [process.argv[2], ...m.STORE_EXT_IDS].map((id) => `chrome-extension://${id}/`))))
' "$REPO/plugin/setup.js" "$EXT_ID")"
mkdir -p "$NM_DIR"
cat > "$NM_FILE" <<JSON
{
  "name": "$HOST_NAME",
  "description": "dsh-chrome-bridge native host (local browser control)",
  "path": "$BRIDGE/host/run.sh",
  "type": "stdio",
  "allowed_origins": $ORIGINS
}
JSON
echo "    $NM_FILE"

echo "==> 4/6 install the cb CLI"
cp "$VENDOR/cb" "$HOME/.dsh/bin/cb"
chmod +x "$HOME/.dsh/bin/cb"

echo "==> 5/6 install the manager command"
cat > "$HOME/.dsh/bin/dsh-chrome-bridge" <<SH
#!/bin/sh
# generated by install.sh — points back at the checkout
exec "$REPO/bridge" "\$@"
SH
chmod +x "$HOME/.dsh/bin/dsh-chrome-bridge"

# ~/.dsh/bin is usually NOT on PATH (the agent's shell would get "cb: command not
# found"), so also link both commands somewhere that is: ~/.local/bin.
# Never clobber the user's own command of the same name: only link when nothing is
# there yet (a link that already points at ours is left as is).
LOCAL_BIN="$HOME/.local/bin"
mkdir -p "$LOCAL_BIN"
link_cmd() {
  if [ -L "$2" ] && [ "$(readlink "$2")" = "$1" ]; then return 0; fi
  if [ -e "$2" ] || [ -L "$2" ]; then
    echo "    $2 already exists and is not ours — left it alone"
    return 0
  fi
  ln -s "$1" "$2"
}
link_cmd "$HOME/.dsh/bin/cb" "$LOCAL_BIN/cb"
link_cmd "$HOME/.dsh/bin/dsh-chrome-bridge" "$LOCAL_BIN/dsh-chrome-bridge"
case ":$PATH:" in
  *":$LOCAL_BIN:"*) echo "    linked into $LOCAL_BIN (already on PATH)" ;;
  *) echo "    linked into $LOCAL_BIN — add it to PATH if commands are not found" ;;
esac

echo "==> 6/6 install the DSH skill"
mkdir -p "$HOME/.dsh/skills/browser"
cp "$VENDOR/skill/SKILL.md" "$HOME/.dsh/skills/browser/SKILL.md"
echo "    ~/.dsh/skills/browser/SKILL.md"

cat <<EOF

Done. One manual step left — you only ever do this once:

  1. open chrome://extensions
  2. turn on "Developer mode" (top right)
  3. click "Load unpacked" and pick this folder:

     $EXT_DIR

  4. no buttons to press afterwards. Verify with:  cb status

Optional — native DSH tools (browser_* instead of shelling out to cb):
  DSH sidebar -> Plugins -> Add plugin -> paste this (it installs the host by itself):

     github:OrderG-X/dsh-chrome-bridge#path:plugin

  then restart DSH (a freshly installed bundle is not hot-loaded).

Extension ID: $EXT_ID (already bound in the native host registration)
EOF
